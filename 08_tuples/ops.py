# Tuple Methods / Operations 

# index(): Used To Get Index Position Of Given Element
data = (10,20,30,40,50)
print(data)
data.index(30)
print(data.index(30))
print(data.index(50))

# count():  Count the number of occurrences of a value
data = (10,20,10,30,10,40,10)
print(data)
data.count(10)
print(data.count(10))

